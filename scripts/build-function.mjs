// Bundles the game into one file for a Railway Function (Bun, no repo needed):
//   node scripts/build-function.mjs   ->   dist/function.ts
// engine.js and table.js are inlined unchanged apart from their import/export keywords,
// so the deployed rules are exactly the tested ones.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const strip = (src) => src
  .replace(/^import[\s\S]*?from '[^']+';\n/gm, '')
  .replace(/^export \{[^}]*\};\n/gm, '')
  .replace(/^export (const|function|class) /gm, '$1 ');

const out = [
  '// GENERATED by scripts/build-function.mjs - edit src/ and public/, then rebuild.',
  "import { randomInt, randomBytes } from 'node:crypto';",
  '',
  '// ---- src/engine.js ----',
  strip(read('src/engine.js')),
  '// ---- src/table.js ----',
  strip(read('src/table.js')),
  '// ---- public/index.html ----',
  `const HTML = ${JSON.stringify(read('public/index.html'))};`,
  '',
  '// ---- src/bun-transport.js ----',
  read('src/bun-transport.js'),
].join('\n');

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/function.ts'), out);
console.log(`dist/function.ts  ${(out.length / 1024).toFixed(1)} KB`);
